#!/usr/bin/env python3
# Writes the basis-set libraries into the built-in Compute programs (Shaders/compute/compute.json) -- basis-sto-3g, basis-6-31g, basis-6-31gd
# -- from the Basis Set Exchange (pip install basis_set_exchange). Each is a library a program takes in; it holds its set's tables and takes
# in "basis", the expansion. Pople sp shells are split into an s and a p shell on the same exponents; d shells are Cartesian (6 functions),
# as the Pople sets define them.
# Usage: python3 basis.py [compute.json]   (default: ../compute.json beside this script)
import json, os, sys
import basis_set_exchange as bse

SETS = [("basis-sto-3g", "STO-3G", "STO-3G"), ("basis-6-31g", "6-31G", "6-31G"), ("basis-6-31gd", "6-31G*", "6-31G* (6-31G(d))")]
ELEMENTS = list(range(1, 19))  # H .. Ar
NAMES = ["", "H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne", "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar"]

store = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "compute.json")
programs = json.load(open(store))


def numbers(values, per_line):
    rows = [", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line)]
    return "    " + ",\n    ".join(rows)


for entry, name, title in SETS:
    data = bse.get_basis(name, elements=ELEMENTS, header=False)
    shells, primitives = [], []
    for z in ELEMENTS:
        element = data["elements"].get(str(z))
        if element is None:
            continue
        for shell in element["electron_shells"]:
            exponents = [float(e) for e in shell["exponents"]]
            for l, coefficients in zip(shell["angular_momentum"], shell["coefficients"]):
                first = len(primitives)
                for e, c in zip(exponents, coefficients):
                    primitives.append((e, float(c)))
                shells.append((z, l, first, len(exponents)))
    have = sorted({z for z, _, _, _ in shells})
    source = f"""// =============================================================================================================================================
// {entry} -- the {title} basis set, {NAMES[have[0]]} to {NAMES[have[-1]]}: its tables, then the expansion (it takes in basis -- read that one for how
// a program uses it). A library: a program takes in one basis set (include {entry}) and gaussian.
// GENERATED by Shaders/compute/tools/basis.py from the Basis Set Exchange {bse.version()} -- run the script, don't edit this.
// Coefficients are on normalized primitives, as published (the expansion renormalizes each contracted shell).
// =============================================================================================================================================

// a shell a row -- Z, l, first primitive, primitive count; an element's rows together, in the set's order
#define IR77_BASIS_SHELL_COUNT {len(shells)}
__constant int IR77_BASIS_SHELLS[IR77_BASIS_SHELL_COUNT * 4] = {{
{numbers([f"{z}, {l}, {first}, {count}" for z, l, first, count in shells], 6)}}};

// a primitive a pair -- exponent, coefficient
__constant double IR77_BASIS_PRIMITIVES[{len(primitives)} * 2] = {{
{numbers([f"{e!r}, {c!r}" for e, c in primitives], 3)}}};

// @include basis
"""
    programs[entry] = {"source": source}

# the store's own form -- one program a line
with open(store, "w") as f:
    f.write("{\n" + ",\n".join(f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in programs.items()) + "\n}\n")
print("wrote", ", ".join(e for e, _, _ in SETS), "into", store)
