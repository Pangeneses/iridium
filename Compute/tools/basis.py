#!/usr/bin/env python3
# Writes services/Ir77BasisSets.hpp -- the basis sets Compute knows, from the Basis Set Exchange (pip install basis_set_exchange).
# Pople sp shells are split into an s and a p shell on the same exponents. d shells are Cartesian (6 functions), as the Pople sets define them.
# Usage: python3 basis.py [out]   (default: ../services/Ir77BasisSets.hpp beside this script)
import os, sys
import basis_set_exchange as bse

SETS = ["STO-3G", "6-31G", "6-31G*"]
ELEMENTS = list(range(1, 19))  # H .. Ar

out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "services", "Ir77BasisSets.hpp")

shells, numbers = [], []
for index, name in enumerate(SETS):
    data = bse.get_basis(name, elements=ELEMENTS, header=False)
    for z in ELEMENTS:
        element = data["elements"].get(str(z))
        if element is None:
            continue
        for shell in element["electron_shells"]:
            exponents = [float(e) for e in shell["exponents"]]
            for l, coefficients in zip(shell["angular_momentum"], shell["coefficients"]):
                first = len(numbers) // 2
                for e, c in zip(exponents, coefficients):
                    numbers += [e, float(c)]
                shells.append((index, z, l, first, len(exponents)))

with open(out, "w") as f:
    f.write(f"""#pragma once

#include <cstdint>

// =============================================================================================================================================
// Ir77BasisSets.hpp -- GENERATED by Compute/tools/basis.py from the Basis Set Exchange {bse.version()}. Do not edit; run the script.
// Sets: {", ".join(SETS)}; elements H .. Ar. Coefficients are on normalized primitives, as published (Compute renormalizes each contracted
// shell). Pople sp shells are split into s and p on the same exponents.
// =============================================================================================================================================

namespace NSIr77Compute {{

inline constexpr char const* BASIS_SET_NAMES[]{{{", ".join('"' + s.lower() + '"' for s in SETS)}}};

inline constexpr std::uint32_t BASIS_SET_COUNT{{{len(SETS)}}};

// one shell of one element in one set -- its primitives are BASIS_PRIMITIVES[first .. first + count), each (exponent, coefficient)
struct Ir77BasisShellRow {{
    std::uint32_t set;
    std::uint32_t z;
    std::uint32_t l;
    std::uint32_t first;
    std::uint32_t count;
}};

inline constexpr Ir77BasisShellRow BASIS_SHELLS[]{{
""")
    for s in shells:
        f.write("    {%d, %d, %d, %d, %d},\n" % s)
    f.write("};\n\ninline constexpr double BASIS_PRIMITIVES[][2]{\n")
    for i in range(0, len(numbers), 2):
        f.write("    {%r, %r},\n" % (numbers[i], numbers[i + 1]))
    f.write("};\n\n}  // namespace NSIr77Compute\n")

print(f"{len(shells)} shells, {len(numbers) // 2} primitives -> {out}")
